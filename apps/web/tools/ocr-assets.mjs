// tools/ocr-assets.mjs — copy the tesseract.js runtime into apps/web/public/tesseract/ so the screenshot
// importer runs fully offline (no CDN). Called by the Vite plugin in vite.config.ts on dev/build start;
// can also be run by hand:  node apps/web/tools/ocr-assets.mjs
//
// Sources (node_modules):  tesseract.js/dist/worker.min.js
//                          tesseract.js-core/tesseract-core{,-simd,-relaxedsimd}-lstm.wasm.js  (LSTM-only builds)
//                          @tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz
// The copies are generated, so the folder carries its own .gitignore.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const FILES = [
  ["tesseract.js/dist/worker.min.js", "worker.min.js"],
  ["tesseract.js-core/tesseract-core-lstm.wasm.js", "tesseract-core-lstm.wasm.js"],
  ["tesseract.js-core/tesseract-core-simd-lstm.wasm.js", "tesseract-core-simd-lstm.wasm.js"],
  ["tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm.js", "tesseract-core-relaxedsimd-lstm.wasm.js"],
  ["@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", "eng.traineddata.gz"],
];

export function syncOcrAssets(webDir, log = () => {}) {
  const nm = path.join(webDir, "node_modules");
  const out = path.join(webDir, "public", "tesseract");
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, ".gitignore"), "# generated by tools/ocr-assets.mjs\n*\n");
  const missing = [];
  let copied = 0;
  for (const [from, to] of FILES) {
    const src = path.join(nm, from);
    const dst = path.join(out, to);
    if (!fs.existsSync(src)) { missing.push(from); continue; }
    const s = fs.statSync(src);
    if (fs.existsSync(dst) && fs.statSync(dst).size === s.size && fs.statSync(dst).mtimeMs >= s.mtimeMs) continue;
    fs.copyFileSync(src, dst);
    copied++;
  }
  if (copied) log(`[ocr-assets] copied ${copied} file(s) to public/tesseract`);
  if (missing.length) log(`[ocr-assets] missing in node_modules (run npm install in apps/web): ${missing.join(", ")}`);
  return { copied, missing };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = syncOcrAssets(path.resolve(import.meta.dirname, ".."), console.log);
  if (r.missing.length) process.exit(1);
}
