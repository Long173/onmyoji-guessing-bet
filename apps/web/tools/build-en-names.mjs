// tools/build-en-names.mjs — 把 data/kb/en-names.json 压成前端可直接 import 的 TS 模块
// 为什么是 .ts 而不是 .json：presenter / engine-adapter 会被 Node 测试直接 import，
// Node 24 对无 import attributes 的 JSON import 会直接报错；TS 对象两边都能用。
// 运行：node apps/web/tools/build-en-names.mjs
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..", "..", "..");
const SRC = path.join(ROOT, "data", "kb", "en-names.json");
const OUT = path.resolve(import.meta.dirname, "..", "src", "kb", "en-names.gen.ts");

const raw = JSON.parse(await fs.readFile(SRC, "utf8"));
const shikigami = {};
for (const [id, v] of Object.entries(raw.shikigami ?? {})) {
  if (v?.en && v?.cn) shikigami[id] = [v.en, v.cn];
}
const souls = {};
for (const [id, v] of Object.entries(raw.souls ?? {})) {
  if (v?.en && v?.cn) souls[id] = [v.en, v.cn];
}

const body = `// AUTO-GENERATED by tools/build-en-names.mjs from data/kb/en-names.json — do not edit by hand.
// Source: ${raw._meta?.source ?? "data/kb/en-names.json"}
// Shape: id -> [English name, Chinese name]
export const SHIKIGAMI_EN: Record<string, readonly [string, string]> = ${JSON.stringify(shikigami)};
export const SOUL_EN: Record<string, readonly [string, string]> = ${JSON.stringify(souls)};
`;
await fs.writeFile(OUT, body, "utf8");
console.log(`en-names.gen.ts: ${Object.keys(shikigami).length} shikigami, ${Object.keys(souls).length} souls`);
