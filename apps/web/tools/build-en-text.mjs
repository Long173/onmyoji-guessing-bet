// tools/build-en-text.mjs — 把 data/kb/en-text.json（KB 文本的英文翻译，扁平 key→value）压成 TS 模块
// 与 build-en-names.mjs 同理：生成 .ts 而不是直接 import JSON（Node 测试直接 import 时 JSON 需要 import attributes）。
//
// key 约定（见 apps/web/src/kb/en-text.ts）：
//   skill:<skillId>:name|brief|desc|up<level>   tip:<id>:name|desc   buff:<id>:name|desc
//   soul:<i>:suit|desc                          tag:<中文标签>
// 值里的 [buff_x] / [tips_x] 占位符保持原样，前端照旧用 resolveRefs 解析。
//
// 容错：源文件缺失 / 解析失败 / 部分条目不是字符串 ⇒ 照样生成（缺的就是空表，前端回退中文），只打警告。
// 运行：node apps/web/tools/build-en-text.mjs
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..", "..", "..");
const SRC = path.join(ROOT, "data", "kb", "en-text.json");
const OUT = path.resolve(import.meta.dirname, "..", "src", "kb", "en-text.gen.ts");

async function readSource() {
  let text;
  try {
    text = await fs.readFile(SRC, "utf8");
  } catch (e) {
    if (e?.code === "ENOENT") {
      console.warn(`en-text: ${path.relative(ROOT, SRC)} not found — generating an empty map (UI falls back to Chinese)`);
      return {};
    }
    throw e;
  }
  try {
    const raw = JSON.parse(text.replace(/^﻿/, ""));
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      console.warn("en-text: source is not a flat JSON object — generating an empty map");
      return {};
    }
    return raw;
  } catch (e) {
    console.warn(`en-text: failed to parse ${path.relative(ROOT, SRC)} (${e.message}) — generating an empty map`);
    return {};
  }
}

const raw = await readSource();
const entries = [];
let skipped = 0;
for (const [k, v] of Object.entries(raw)) {
  if (k.startsWith("_")) continue; // _meta 等
  if (typeof v !== "string" || !v.trim()) { skipped++; continue; }
  entries.push([k, v]);
}
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const map = Object.fromEntries(entries);

const body = `// AUTO-GENERATED by tools/build-en-text.mjs from data/kb/en-text.json — do not edit by hand.
// Shape: flat key -> English text (keys documented in src/kb/en-text.ts). Missing keys fall back to Chinese.
export const EN_TEXT: Record<string, string> = ${JSON.stringify(map, null, 0)};
`;
await fs.writeFile(OUT, body, "utf8");
console.log(`en-text.gen.ts: ${entries.length} keys${skipped ? `, ${skipped} skipped (non-string or empty)` : ""}`);

// ── en-engine.gen.ts: Chinese name → English for display-time translation of engine strings ──
// The engine, replays and hand-written betting kits carry Chinese skill / status / field names.
// KB_*_EN map every KB skill / status (buff, tip) name and tag to the English above (first id wins on a clash);
// ENGINE_TERMS / ENGINE_SENTENCES come from data/kb/en-engine-terms.json (terms that only exist in betting kits,
// engine log phrases, AI conditions). Consumers: apps/web/src/kb/en-engine.ts.
async function readJson(rel, dflt) {
  try { return JSON.parse((await fs.readFile(path.join(ROOT, rel), "utf8")).replace(/^﻿/, "")); }
  catch (e) { console.warn(`en-engine: ${rel} unreadable (${e.message}) — using an empty table`); return dflt; }
}
const kbSkill = {}, kbStatus = {}, kbTag = {};
const putName = (tbl, cn, en) => {
  if (!cn || !en || !/[㐀-鿿]/.test(cn)) return;
  if (tbl[cn] === undefined) tbl[cn] = en;
};
for (const sh of await readJson("data/kb/shikigami.full.json", [])) for (const k of sh.skills ?? []) putName(kbSkill, k.name, map[`skill:${k.id}:name`]);
for (const b of await readJson("data/kb/buffs.json", [])) putName(kbStatus, b.name, map[`buff:${b.id}:name`]);
for (const t of await readJson("data/kb/tips.json", [])) putName(kbStatus, t.name, map[`tip:${t.id}:name`]);
for (const [k, v] of entries) if (k.startsWith("tag:")) putName(kbTag, k.slice(4), v);
const terms = await readJson("data/kb/en-engine-terms.json", {});
const flat = (o) => Object.fromEntries(Object.entries(o ?? {}).filter(([k, v]) => !k.startsWith("_") && typeof v === "string"));
const engineTerms = flat(terms.terms);
const engineSentences = flat(terms.sentences);
const sortObj = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const OUT2 = path.resolve(import.meta.dirname, "..", "src", "kb", "en-engine.gen.ts");
await fs.writeFile(OUT2, `// AUTO-GENERATED by tools/build-en-text.mjs from data/kb/{en-text,shikigami.full,buffs,tips,en-engine-terms}.json — do not edit by hand.
// KB_SKILL_EN / KB_STATUS_EN (buffs + tips) / KB_TAG_EN: KB names (Chinese) -> English (first id wins). ENGINE_TERMS: phrases used inside engine strings.
// ENGINE_SENTENCES: whole strings matched exactly (AI conditions, engine notes). See src/kb/en-engine.ts.
export const KB_SKILL_EN: Record<string, string> = ${JSON.stringify(sortObj(kbSkill))};
export const KB_STATUS_EN: Record<string, string> = ${JSON.stringify(sortObj(kbStatus))};
export const KB_TAG_EN: Record<string, string> = ${JSON.stringify(sortObj(kbTag))};
export const ENGINE_TERMS: Record<string, string> = ${JSON.stringify(sortObj(engineTerms))};
export const ENGINE_SENTENCES: Record<string, string> = ${JSON.stringify(sortObj(engineSentences))};
`, "utf8");
console.log(`en-engine.gen.ts: ${Object.keys(kbSkill).length} skill / ${Object.keys(kbStatus).length} status / ${Object.keys(kbTag).length} tag names, ${Object.keys(engineTerms).length} terms, ${Object.keys(engineSentences).length} sentences`);
